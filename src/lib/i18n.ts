export function t(locale: Locale, key: string, params?: Record<string, string | number>): string {
  let s = STRINGS[locale]?.[key] ?? STRINGS.ko[key] ?? key;
  if (params) {
    for (const k of Object.keys(params)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(params[k]));
    }
  }
  return s;
}

/** 현재 로케일 기준 번역 함수 훅 */
export function useT() {
  const locale = useTripStore((s) => s.locale);
  return (key: string, params?: Record<string, string | number>) => t(locale, key, params);
}

export function useLocale(): Locale {
  return useTripStore((s) => s.locale);
}

/** 부분 번역 데이터에서 현재 로케일 값을 고르되, 없으면 en→ko 순으로 폴백 */
export type Localized = Partial<Record<Locale, string>>;
export function pick(l: Localized, locale: Locale): string {
  return l[locale] ?? l.en ?? l.ko ?? '';
}
